import {readFile,lstat,realpath} from 'node:fs/promises';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {runtimeFiles} from './files.mjs';
import {validateReference,emptyWorkspace,validateWorkspace,safeOfficialUrl} from '../src/domain.js';
export const project=fileURLToPath(new URL('../',import.meta.url));
export async function validatedInputs(root=project){
 const realRoot=await realpath(root),buffers=new Map();
 for(const [dest,src]of Object.entries(runtimeFiles)){
  assert(!path.isAbsolute(dest)&&!path.isAbsolute(src)&&!dest.split('/').includes('..')&&!src.split('/').includes('..'),'Unsafe allowlist');
  let step=root;for(const part of src.split('/')){step=path.join(step,part);assert(!(await lstat(step)).isSymbolicLink(),'Symlink not accepted: '+src);}
  assert((await lstat(step)).isFile()&&(await realpath(step)).startsWith(realRoot+path.sep),'Not a safe input: '+src);
  buffers.set(dest,await readFile(step));
 }
 const json=d=>JSON.parse(buffers.get(d).toString());
 const reference=validateReference(json('data/reference.json'));
 validateWorkspace(emptyWorkspace(reference),reference);
 const profile=json('data/local-profile.json');
 assert.equal(profile.app,'arzttarife.local-catalog');assert.equal(profile.version,1);assert.equal(profile.edition,'2026-1.4c-1.1c');
 assert.deepEqual(profile.counts,{tardoc:1388,pauschalen:314});assert.equal(profile.contexts,9);assert(/^[a-f0-9]{64}$/.test(profile.sha256));assert.equal(profile.bytes,3113099);
 const provenance=json('data/provenance.json');assert.equal(provenance.schemaVersion,1);assert.equal(provenance.edition,'2026');
 const pins=JSON.parse(await readFile(path.join(root,'scripts/source-pins.json')));
 for(const f of provenance.files){assert(safeOfficialUrl(f.url)&&safeOfficialUrl(f.final_url),'Unsafe source URL');assert(/^[a-f0-9]{64}$/.test(f.sha256));assert(Number.isSafeInteger(f.bytes)&&f.bytes>0);assert(!f.file.includes('/')&&!f.file.includes('..'));assert(Number.isFinite(Date.parse(f.retrieved_at)));}
 for(const pin of pins){const p=provenance.files.find(p=>p.file===pin.file);assert.deepEqual(p,pin);assert.equal(profile.sources.find(s=>s.id===pin.file.split('.')[0]).sha256,pin.sha256);}
 const html=buffers.get('index.html').toString();
 const canon=[...html.matchAll(/href="(https:\/\/wakuwakumiwaku.github.io\/[^"/]+\/)"/g)].map(m=>m[1]);
 assert.equal(canon.length,9);assert.equal(new Set(canon).size,9);assert.equal((html.match(/aria-current="page"/g)||[]).length,1);
 for(const id of ['search','results','detail-dialog','more','reset'])assert(html.includes(`id="${id}"`));
 assert(!/https?:\/\/(?:fonts\.|.*analytics)/i.test(html));
 const js=buffers.get('src/app.js').toString();assert(!/innerHTML|insertAdjacentHTML|document\.write/.test(js));assert(js.includes("document.body.dataset.ready='true'"));
 for(const [dest,b]of buffers)if(/\.(html|js|css|json|svg)$/.test(dest))assert(!/\/mnt\/[a-z]\/|\/home\/hermes|generated by|OpenAI|ChatGPT|Hermes Agent/i.test(b.toString()),'Private path or attribution in '+dest);
 return buffers;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
 for(const file of ['src/app.js','src/domain.js','scripts/build.mjs','scripts/serve.mjs','scripts/check.mjs','scripts/files.mjs','tests/import-intent.test.mjs','tests/helpers/import-platform.mjs','tests/browser.mjs'])execFileSync(process.execPath,['--check',path.join(project,file)],{stdio:'pipe'});
 const b=await validatedInputs();console.log(`OK: ${b.size} explicit runtime inputs; 16 references, 9 official documents; local catalog not distributed.`);
}
